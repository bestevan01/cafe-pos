-- 저울 최대 무게를 넘는 통을 '이 이상'으로 기록한다. (서버 기동 때 server.js가 자동으로 적용한다 — 이 파일은 기록용)
--
-- 매장 저울은 1000g까지만 잰다. 베이스는 가득 차면 1200g + 통 120g, 딸기청은 1000g + 통 85g이라
-- 거의 가득 찬 통은 잴 수 없다. 그때 저울에 뜬 숫자를 그대로 적으면 거짓 값이 된다.
--  - 직원이 '넘침'을 누르거나 저울 최대 무게 이상을 적으면 quantity에 저울 최대 무게를 넣고
--    over_scale = 1로 표시한다. 뜻은 '이 무게 이상'이다(예: 베이스 순 880g 이상).
--  - 주문 판단: 잴 수 있는 최솟값이 기준보다 많으면 확실히 충분하다. 기준이 저울 한계보다 높으면
--    판단할 수 없어 관리자 화면이 기준을 낮추라고 안내한다.
--  - 직전 회차와의 증감은 둘 다 실제로 잰 값일 때만 낸다.
--
-- 저울 최대 무게는 매장 설정(store_settings.scale_max_g)이다. 없으면 1000g으로 본다.

ALTER TABLE inventory_count_items
    ADD COLUMN over_scale TINYINT(1) NOT NULL DEFAULT 0 AFTER spare_count;
