-- 메뉴 표시 순서.
--
-- menu.id가 UUID라 지금까지는 정렬 기준이 아예 없었다. `SELECT * FROM menu`가 돌려주는
-- 순서는 UUID 값에 따라 사실상 무작위여서, 캐셔 화면의 메뉴 배치가 매장마다 다르고
-- 메뉴를 하나 추가하면 엉뚱한 자리에 끼어들었다. 관리자가 직접 순서를 정할 수 있게 한다.
--
-- 분류(type)별이 아니라 '전체 하나의 순서'인 이유: 캐셔 화면이 분류 탭 없이
-- 전체 메뉴를 한 그리드에 평면으로 그린다. 분류별 순서를 따로 두면 화면에 반영할
-- 자리가 없다. 관리자가 같은 분류끼리 붙여 놓고 싶으면 그렇게 끌어다 놓으면 된다.
--
-- 기존 행은 backfill하지 않는다. 전부 0이어도 조회 쿼리가 `ORDER BY sort_order, name`이라
-- 이름순으로 안정적으로 나오고, 관리자가 처음 순서를 바꾸는 순간 화면에 보이던 순서
-- 그대로 1..N이 한 번에 기록된다. 굳이 미리 번호를 매겨 둘 이유가 없다.
--
-- 새로 추가되는 메뉴는 서버가 MAX(sort_order)+1을 넣는다. DEFAULT 0을 그대로 두면
-- 순서를 정해 둔 매장에서 새 메뉴가 매번 맨 위로 튀어 오른다.

ALTER TABLE menu
    ADD COLUMN sort_order INT NOT NULL DEFAULT 0;
