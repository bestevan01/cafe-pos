-- 회차마다 적용 요일을 둔다. (서버 기동 때 server.js가 자동으로 적용한다 — 이 파일은 기록용)
--
-- 요일마다 운영 시간이 다르다. 예) 월~수 9~17시, 목 9~16시, 금 미운영.
-- 회차 목록이 하나뿐이면 목요일 마감 조사(15시 반쯤)가 15시 회차로 들어가 이미 낸 기록을 덮어쓰고,
-- 금요일에도 17시 알림 시각이 돌아간다. 그래서 회차마다 적용 요일을 고른다.
--  - 경계는 '그날 적용되는 회차끼리'만 계산한다(목요일은 15시·16시의 가운데 15:30).
--  - 그날 적용되는 회차가 없으면 미운영일 — 시각 알림과 관리자 확인 알림을 보내지 않는다.
--    누가 나와 기록하는 것까지 막지는 않는다(전체 회차 중 시각에 맞는 회차로 기록된다).
--  - 위생 점검 보고서는 회차 이력(hygiene_slot_plans)에 요일도 남겨, 날짜마다 그날 요일의 회차만 그린다.
--    요일 정보가 없는 옛 이력은 예전처럼 평일만 운영일로 본다.
--
-- days는 ISO 요일 숫자를 이어 붙인 문자열이다('1'=월 … '7'=일). 기존 회차는 매일('1234567')로 둔다 —
-- 지금까지 매일 적용되던 것과 같다. 요일 판단은 DB의 WEEKDAY(CURDATE())로 한다(서버는 UTC로 돈다).

ALTER TABLE inventory_slots
    ADD COLUMN days VARCHAR(7) NOT NULL DEFAULT '1234567' AFTER run_at;

