-- 주방의 항목별 중간 체크.
--
-- 한 주문에 음료가 여러 잔이면 만들다가 어디까지 했는지 놓치기 쉽다. 특히 둘이 나눠 만들 때
-- 같은 잔을 두 번 만들거나 한 잔을 빠뜨리는 일이 생긴다. 그래서 잔 단위로 체크를 남긴다.
--
-- orders 테이블은 '주문 한 건'이 아니라 '주문의 한 품목'이 한 행이다(같은 display_id를 공유).
-- 그래서 체크도 행에 그대로 붙이면 된다. 별도 테이블이 필요 없다.
--
-- 서버 메모리에 두지 않는 이유: Render 무료 요금제는 트래픽이 없으면 서버를 재웠다 깨우고,
-- 그때 메모리가 날아간다. 만들던 중에 체크가 통째로 풀리면 없느니만 못하다.
--
-- is_completed와의 관계: 조리 완료는 여전히 사람이 직접 누른다. 전부 체크됐다고 자동으로
-- 넘기지 않는다 — 잘못 체크했을 때 되돌릴 수 있어야 하고, 컵에 담아 내보내는 마지막 확인이
-- 한 번은 필요하다. 체크는 어디까지 했는지 보여주는 표시일 뿐이다.
--
-- 조리가 끝나면(is_completed=1) 주방 목록에서 빠지므로 이 값은 더 쓰이지 않는다. 굳이 되돌리지 않는다.

ALTER TABLE orders
    ADD COLUMN is_made TINYINT(1) NOT NULL DEFAULT 0;
