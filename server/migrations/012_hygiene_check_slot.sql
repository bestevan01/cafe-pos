-- 위생 점검을 하루 2회(오전·오후)로 나눈다.
--
-- 처음에는 '아침에 한 번, 전날 마감이 제대로 됐는지 확인'이 목적이라 하루 1건으로 못을 박았다.
-- 운영 가이드라인이 오전·오후 2회로 정해지면서 그 전제가 깨졌다. 지금 구조에서 오후에
-- 점검하면 새 기록이 아니라 오전 기록을 덮어써, 오전 결과가 사라진다.
--
-- 시각(9시/16시)이 아니라 'am'/'pm' 두 칸으로 두는 이유:
-- 매장마다 오후 시각이 다르고(본부동 16시 · 은혜관 17시) 실제로는 늦어질 수도 있다.
-- 시각을 조건으로 걸면 16시 5분에 한 점검이 어느 칸에도 안 들어간다.
-- 칸은 사람이 정하고, 현재 시각은 기본값을 제안하는 데만 쓴다.
--
-- 기존 기록은 DEFAULT 'am'으로 들어간 뒤, 실제 제출 시각(checked_at)을 보고 오후 것만 바로잡는다.
-- 전부 아침 점검일 거라 여겼는데 실제로는 16:29, 13:22처럼 오후에 낸 기록도 있었다.
-- 시각을 무시하고 전부 오전으로 두면 보고서에 '오전 김서연 16:29'처럼 앞뒤가 안 맞는 줄이 남는다.
--
-- ⚠️ 이 UPDATE는 컬럼을 처음 만들 때 딱 한 번만 돌아야 한다. 부팅마다 돌리면, 아침 점검을
-- 늦게(오후에) 제출한 경우처럼 사람이 일부러 고른 칸을 시각만 보고 덮어쓴다.

ALTER TABLE hygiene_checks
    ADD COLUMN slot VARCHAR(10) NOT NULL DEFAULT 'am';

-- ⚠️ 순서가 중요하다. 새 키를 먼저 만들고 옛 키를 지운다.
-- 반대로 하면 지운 뒤 새 키 생성이 실패했을 때 중복 방지 장치가 아예 없는 상태가 된다.
ALTER TABLE hygiene_checks
    ADD UNIQUE KEY uq_hygiene_checks_date_slot (check_date, slot);

-- 옛 키는 반드시 지워야 한다. 남아 있으면 날짜당 1건 제약이 유지되어 오후 점검이 막힌다.
ALTER TABLE hygiene_checks
    DROP INDEX uq_hygiene_checks_date;

-- 컬럼을 새로 만든 직후 한 번만 실행한다(위 주석 참고).
-- 경계는 정오. routes/hygiene.routes.js의 PM_FROM_HOUR와 같아야 한다 —
-- 다르면 과거 기록과 앞으로 쌓일 기록의 기준이 달라진다.
UPDATE hygiene_checks
SET slot = 'pm'
WHERE HOUR(checked_at) >= 12;
